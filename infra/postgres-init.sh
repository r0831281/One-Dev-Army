#!/bin/sh
set -eu
psql --set ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" <<-SQL
  REVOKE CONNECT ON DATABASE temporal FROM PUBLIC;
  GRANT CONNECT, TEMPORARY ON DATABASE temporal TO oda_temporal;
  CREATE ROLE oda_product LOGIN PASSWORD '${ODA_PRODUCT_DB_PASSWORD}' NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT;
  CREATE DATABASE oda_product OWNER oda_product;
  REVOKE ALL ON DATABASE oda_product FROM PUBLIC;
  GRANT CONNECT, TEMPORARY ON DATABASE oda_product TO oda_product;
SQL
